    <h2>About this song...</h2>
    <p>
      <strong>You Are On The Throne</strong> is a sung walk through the opening
      of John's Gospel. The verses follow John 1 almost line for line, moving
      from the eternal Word, to the Word made flesh, to the cross. The chorus
      and bridge then land where the rest of the New Testament lands: Jesus,
      crucified and raised, is now seated on the throne of heaven.
    </p>
    <p>
      Verse 1 is John 1:1-4 set to music. The Word was already there at the
      start. He was with God, He was God, everything was made through Him, and
      He is the source of life and light.
    </p>
    <blockquote class="scripture">
      <p>
        <sup>1</sup> In the beginning was the Word, and the Word was with God,
        and the Word was God. <sup>2</sup> He was in the beginning with God.
        <sup>3</sup> All things were made through him, and without him was not
        any thing made that was made. <sup>4</sup> In him was life, and the
        life was the light of men. <sup>5</sup> The light shines in the
        darkness, and the darkness has not overcome it.
      </p>
      <p>John 1:1-5 ESV</p>
    </blockquote>
    <p>
      Verse 2 picks up at verse 5 and carries on to verse 14. The light keeps
      shining and the darkness has no power to put it out. Then the Word, who
      is God, becomes flesh and dwells among us, full of grace and truth.
      "Dwelling here" is John's own language: the eternal Word did not stay at a
      distance but came and made His home with us.
    </p>
    <blockquote class="scripture">
      <p>
        <sup>14</sup> And the Word became flesh and dwelt among us, and we have
        seen his glory, glory as of the only Son from the Father, full of grace
        and truth.
      </p>
      <p>John 1:14 ESV</p>
    </blockquote>
    <p>
      The pre-chorus and chorus are our response to who the Word is. Hebrews
      opens by describing the Son in the same terms John does, as the one
      through whom God made and sustains all things, and then tells us where He
      is now: seated at the right hand of the Father.
    </p>
    <blockquote class="scripture">
      <p>
        <sup>3</sup> He is the radiance of the glory of God and the exact
        imprint of his nature, and he upholds the universe by the word of his
        power. After making purification for sins, he sat down at the right
        hand of the Majesty on high,
      </p>
      <p>Hebrews 1:3 ESV</p>
    </blockquote>
